/** 一份原始文档。检索命中的是它切出来的 chunk，引用要能顺着 sourceId 回到这里。 */
export interface Source {
  sourceId: string
  sourceTitle: string
  text: string
}

/** 切出来的一块。chunkId 是引用体系里唯一的定位符，形如 s07#1。 */
export interface Chunk {
  chunkId: string
  sourceId: string
  sourceTitle: string
  content: string
}

// 切块口径：512 字符 + 64 重叠。D12 用的是 400 + 80，本天有了评估集之后重新标定，
// 理由见正文最后一节——参数不是拍脑袋定的，是拿 recall 量出来的。
export const CHUNK_SIZE = 512
export const OVERLAP = 64

/** 来自 D12（`src/memory.ts`），只把两个常量换成本天的口径，逻辑一行没改。 */
export function chunkText(text: string): string[] {
  const chunks: string[] = []
  let start = 0
  while (start < text.length) {
    let end = Math.min(start + CHUNK_SIZE, text.length)
    if (end < text.length) {
      // 只在后半段找边界：在前半段收尾会把块切得太小，反而丢上下文
      const half = start + Math.floor(CHUNK_SIZE / 2)
      const window = text.slice(half, end)
      const hit = Math.max(window.lastIndexOf('。'), window.lastIndexOf('\n'))
      if (hit >= 0) end = half + hit + 1
    }
    const piece = text.slice(start, end).trim()
    if (piece.length > 0) chunks.push(piece)
    if (end >= text.length) break
    // 回退 OVERLAP 制造重叠，同时保证 start 一定前进——否则死循环
    start = Math.max(end - OVERLAP, start + 1)
  }
  return chunks
}

export function buildChunks(sources: Source[]): Chunk[] {
  const out: Chunk[] = []
  for (const source of sources) {
    chunkText(source.text).forEach((content, index) => {
      out.push({
        chunkId: `${source.sourceId}#${index}`,
        sourceId: source.sourceId,
        sourceTitle: source.sourceTitle,
        content,
      })
    })
  }
  return out
}

