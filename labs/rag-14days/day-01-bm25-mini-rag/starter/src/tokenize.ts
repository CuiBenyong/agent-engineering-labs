/**
 * 中英混合分词。
 *
 * 中文没有空格，所以不能像英文那样按空白切。最省事也最常用的办法是**二元组**（bigram）：
 * 「回收站」切成「回收」「收站」两个词元，查询里出现「回收站」时同样切成这两个，
 * 于是不用任何词典就能把查询和正文对上。
 */
export function tokenize(text: string): string[] {
  // 练习 1：实现中英混合分词。
  //   - 用 /[一-鿿]+|[a-z0-9]+/g 先把连续的中文段和连续的英文数字段切出来（记得先转小写）
  //   - 中文段按二元组展开：长度为 1 的整段作为一个词元，否则取每两个相邻字
  //   - 英文数字段直接作为一个词元，长度为 1 的（a、5）区分度太低，丢掉
  // 提示：下面这行是「假装自己会分词」的写法——它对英文勉强能用，对中文完全无效，
  //       因为整句中文没有空格，会变成一个谁也匹配不上的巨型词元。
  //       跑一次 pnpm start，你会看到每个问题都是「倒排索引里一个词都没命中」。
  return text.toLowerCase().split(/\s+/).filter(Boolean)
}
