/** 一条三条判据齐全的高质量回复。 */
function strong(order: string, amount: string): Answer {
  return {
    text: `已为订单 ${order} 办理退款，金额 ${amount} 元。该订单在 30 天退款期限内，符合退款政策，款项预计 3 个工作日到账。`,
  }
}

/** 势均力敌的一方：满足「说清结果」与「给出下一步」两条。 */
function even(order: string, amount: string): Answer {
  return { text: `已为订单 ${order} 办理退款，金额 ${amount} 元，预计 3 个工作日到账。` }
}

/** 势均力敌的另一方：同样满足那两条，只是措辞不同、长度相近。 */
function evenAlt(order: string, amount: string): Answer {
  return { text: `订单 ${order} 的 ${amount} 元已为您办理退款，款项很快会到账。` }
}

/** 一条明显更差的回复：只碰到一条判据。 */
function weak(order: string): Answer {
  return { text: `订单 ${order} 的情况我看到了，稍后会有同事跟进，请您留意。` }
}

